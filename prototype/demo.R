source("prototype/compare.R")
paths <- file.path("raw", c("OSD-37.csv", "OSD-38.csv", "OSD-120.csv"))
snapshots <- lapply(paths, read_osdr_snapshot)
normalised <- lapply(snapshots, harmonise_plant_metadata)
col_data <- do.call(rbind, lapply(normalised, `[[`, "col_data"))
provenance <- do.call(rbind, lapply(normalised, `[[`, "provenance"))
completeness <- summarise_completeness(provenance)
pairwise <- compare_study_profiles(col_data)
write.csv(col_data, "results/col_data.csv", row.names = FALSE, na = "")
write.csv(provenance, "results/provenance.csv", row.names = FALSE, na = "")
write.csv(completeness, "results/completeness.csv", row.names = FALSE)
write.csv(pairwise, "results/pairwise.csv", row.names = FALSE)
capture.output(sessionInfo(), file = "results/sessionInfo.txt")
print(table(col_data$accession))
print(pairwise)
cat("Outputs are metadata diagnostics, NOT scientific eligibility decisions.\n")
design <- summarise_design(col_data)
write.csv(design, "results/design_cells.csv", row.names = FALSE)
